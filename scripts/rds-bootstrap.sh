#!/usr/bin/env bash
# Idempotent bootstrap for the RDS IAM auth users. Safe to run on every make up.
#   - fastapi: login role with rds_iam, for the application
#   - oncall:  login role with rds_iam, and database oncall owned by it. Ownership is what
#              lets the store's migrations create tables in public (PostgreSQL 15+)
set -euo pipefail

echo "  Fetching RDS host from terraform output..."
RDS_HOST=$(cd terraform && terraform output -raw rds_host)

echo "  Fetching master password from Secrets Manager..."
SECRET_JSON=$(aws secretsmanager get-secret-value \
  --secret-id platformcore/db/master \
  --region us-east-1 \
  --query SecretString \
  --output text)
MASTER_PASS=$(echo "$SECRET_JSON" | python3 -c "import sys,json; print(json.load(sys.stdin)['password'])")

echo "  Launching rds-bootstrap pod..."
# SQL travels in an env var and reaches psql on stdin, so no shell layer re-processes it.
# $body$ instead of $$: identical to PostgreSQL, meaningless to bash and kubectl.
# CREATE DATABASE cannot run inside a transaction or a DO block, so it is generated by a
# SELECT and executed with \gexec, which runs nothing when the database already exists.
read -r -d '' SQL <<'SQL_EOF' || true
DO $body$ BEGIN
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'fastapi') THEN CREATE USER fastapi WITH LOGIN; END IF;
  IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'oncall') THEN CREATE USER oncall WITH LOGIN; END IF;
END $body$;
GRANT rds_iam TO fastapi;
GRANT rds_iam TO oncall;
-- PostgreSQL 16+: a non-superuser creator (the RDS master) cannot create a database owned
-- by a role it cannot SET ROLE to. Without this the CREATE DATABASE below fails.
GRANT oncall TO CURRENT_USER;
SELECT 'CREATE DATABASE oncall OWNER oncall'
  WHERE NOT EXISTS (SELECT FROM pg_database WHERE datname = 'oncall') \gexec
SQL_EOF

# shellcheck disable=SC2016  # expanded by the pod's shell, not this one
kubectl run rds-bootstrap \
  --image=postgres:17 \
  --restart=Never \
  --env="PGPASSWORD=${MASTER_PASS}" \
  --env="RDS_HOST=${RDS_HOST}" \
  --env="BOOTSTRAP_SQL=${SQL}" \
  -- sh -c 'printf "%s\n" "$BOOTSTRAP_SQL" | psql -v ON_ERROR_STOP=1 -h "$RDS_HOST" -U platformcore -d platformcore -f -'

echo "  Waiting for pod to complete..."
while [[ $(kubectl get pod rds-bootstrap -o jsonpath='{.status.phase}') =~ ^(Pending|Running)$ ]]; do
  sleep 2
done

kubectl logs rds-bootstrap

PHASE=$(kubectl get pod rds-bootstrap -o jsonpath='{.status.phase}')
kubectl delete pod rds-bootstrap --ignore-not-found >/dev/null

if [[ "$PHASE" != "Succeeded" ]]; then
  echo "ERROR: rds-bootstrap pod failed (phase: $PHASE)"
  exit 1
fi

echo "  RDS IAM auth users ready: fastapi, oncall (database oncall)."
