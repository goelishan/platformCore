"""
Renders the cluster manifests from the local sources.

  - prometheus/rules/oncall-llm.rules.yml becomes a PrometheusRule labelled for the
    kube-prometheus-stack release, so the operator loads exactly the rules promtool tested.
  - grafana/dashboards/*.json become one ConfigMap the Grafana sidecar picks up.
  - The outputs are committed and a test fails when they drift from the sources, so a
    rule edited in one place and not the other cannot reach a cluster.
  - Not applied yet. OncallJournalExporterDown fires on an absent target, so these go in
    with the exporter's Deployment and Service, not before.

    make -C oncall obs-render
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent
RULES = ROOT / "prometheus" / "rules" / "oncall-llm.rules.yml"
DASHBOARDS = ROOT / "grafana" / "dashboards"
OUT = ROOT / "k8s"

# Must match helm/monitoring/values.yaml: ruleSelector, and the namespace kps runs in,
# which is the only one the Grafana sidecar watches by default.
RELEASE = "kps"
AGENT_NAMESPACE = "oncall"
MONITORING_NAMESPACE = "monitoring"

HEADER = """\
# Generated by oncall/observability/render.py from {source}.
# Edit the source and run make -C oncall obs-render; a test fails if this file drifts.
"""

LABELS = {"app.kubernetes.io/name": "oncall-agent", "app.kubernetes.io/component": "observability"}


def prometheus_rule() -> str:
    groups = yaml.safe_load(RULES.read_text())["groups"]
    manifest = {
        "apiVersion": "monitoring.coreos.com/v1",
        "kind": "PrometheusRule",
        "metadata": {
            "name": "oncall-llm",
            "namespace": AGENT_NAMESPACE,
            "labels": {**LABELS, "release": RELEASE},
        },
        "spec": {"groups": groups},
    }
    return HEADER.format(source=RULES.relative_to(ROOT)) + _dump(manifest)


def dashboard_configmap() -> str:
    files = sorted(DASHBOARDS.glob("*.json"))
    manifest = {
        "apiVersion": "v1",
        "kind": "ConfigMap",
        "metadata": {
            "name": "oncall-dashboards",
            "namespace": MONITORING_NAMESPACE,
            "labels": {**LABELS, "grafana_dashboard": "1"},
        },
        # Re-serialised compactly: a ConfigMap is capped at 1 MiB and indentation is waste.
        "data": {f.name: json.dumps(json.loads(f.read_text()), separators=(",", ":"))
                 for f in files},
    }
    return HEADER.format(source=DASHBOARDS.relative_to(ROOT)) + _dump(manifest)


def rendered() -> dict[Path, str]:
    return {
        OUT / "prometheusrule.yaml": prometheus_rule(),
        OUT / "grafana-dashboards.yaml": dashboard_configmap(),
    }


def _dump(manifest: dict) -> str:
    return yaml.safe_dump(manifest, sort_keys=False, width=100, allow_unicode=True)


def main() -> int:
    OUT.mkdir(exist_ok=True)
    for path, text in rendered().items():
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT.parent.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
